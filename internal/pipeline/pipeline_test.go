// project creates a throwaway project: dalforge.yaml plus fixture protos
// copied from the loader's testdata.
func project(t *testing.T, yaml string, protos ...string) *config.Config {
	t.Helper()
	dir := t.TempDir()
	write(t, filepath.Join(dir, config.DefaultFile), yaml)
	for _, p := range protos {
		src, err := os.ReadFile(filepath.Join("..", "idl", "testdata", filepath.FromSlash(p)))
		if err != nil {
			t.Fatal(err)
		}
		write(t, filepath.Join(dir, "proto", filepath.FromSlash(p)), string(src))
	}
	cfg, err := config.Load(filepath.Join(dir, config.DefaultFile))
	if err != nil {
		t.Fatal(err)
	}
	return cfg
}

func write(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

const _yaml = "version: 1\nmodule: example.com/shop\npg:\n  version: \"16.9\"\n"

func TestBuildPlansFiles(t *testing.T) {
	cfg := project(t, _yaml+"out:\n  sqlc: internal/db\n  dal: internal/dal\n", "orders/v1/orders.proto")
	plan, err := Build(context.Background(), cfg)
	if err != nil {
		t.Fatal(err)
	}
	if len(plan.Diags) > 0 {
		t.Fatalf("findings:\n%s", plan.Diags)
	}
	var got []string
	for p := range plan.Files {
		got = append(got, p)
	}
	slices.Sort(got)
	want := []string{
		"internal/dal/orders/v1/ordersdal/dal.go",
		"internal/dal/orders/v1/ordersdal/repository.go",
		"queries/generated/orders.sql",
		"schema/schema.sql",
		"sqlc.yaml",
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("planned files:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	// The custom layout flows through: sqlc's package and the DAL's import.
	if !strings.Contains(string(plan.Files["sqlc.yaml"]), "package: db") ||
		!strings.Contains(string(plan.Files["internal/dal/orders/v1/ordersdal/dal.go"]), `"example.com/shop/internal/db"`) {
		t.Error("custom out.sqlc must set sqlc's package and the DAL's import path")
	}
}

func TestBuildStopsOnFindings(t *testing.T) {
	cfg := project(t, _yaml, "orders/v1/orders.proto")
	// An IDL error the core checks catch: a typo in a list's eq.
	p := cfg.Path("proto/orders/v1/orders.proto")
	src, _ := os.ReadFile(p)
	write(t, p, strings.Replace(string(src), `eq: ["account_id"]`, `eq: ["acount_id"]`, 1))

	plan, err := Build(context.Background(), cfg)
	if err != nil {
		t.Fatal(err)
	}
	if !plan.Diags.HasErrors() || len(plan.Files) != 0 || !strings.Contains(plan.Diags.String(), "DAL117") {
		t.Errorf("want a DAL117 error and no planned files; got %d files and:\n%s", len(plan.Files), plan.Diags)
	}
}

