func TestProtoFiles(t *testing.T) {
	cfg := project(t, _yaml, "orders/v1/orders.proto", "shop/v1/account.proto", "shop/v1/stores.proto")
	// A vendored copy of the options must never become an input.
	write(t, cfg.Path("proto/dal/v1/options.proto"), "syntax = \"proto3\";\n")

	all, err := protoFiles(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.Join(all, ","); got != "orders/v1/orders.proto,shop/v1/account.proto,shop/v1/stores.proto" {
		t.Errorf("default discovery = %s", got)
	}

	cfg.Proto.Files = []string{"shop/v1/*.proto"}
	some, err := protoFiles(cfg)
	if err != nil || strings.Join(some, ",") != "shop/v1/account.proto,shop/v1/stores.proto" {
		t.Errorf("glob = %v, %v", some, err)
	}

	cfg.Proto.Files = []string{"nothing/*.proto"}
	if _, err := protoFiles(cfg); err == nil {
		t.Error("no matching files must be an error")
	}
}

func sqlcOrSkip(t *testing.T) string {
	t.Helper()
	p, err := FindSQLC()
	if err != nil {
		if os.Getenv("CI") != "" {
			t.Fatal(err)
		}
		t.Skip(err)
	}
	return p
}

func TestGenerate(t *testing.T) {
	sqlc := sqlcOrSkip(t)
	ctx := context.Background()
	cfg := project(t, _yaml, "orders/v1/orders.proto")

	// Pre-existing files: a stale generated file, a hand-written file inside
	// a generated directory (no header), and a custom query.
	write(t, cfg.Path("queries/generated/old.sql"), "-- Code generated by dalforge. DO NOT EDIT.\n-- stale\n")
	write(t, cfg.Path("queries/generated/NOTES.md"), "hand-written, keep me\n")
	custom := "-- name: OrderCountByStatus :one\nSELECT count(*) FROM orders WHERE status = @status;\n"
	write(t, cfg.Path("queries/custom/reports.sql"), custom)

	plan, err := Build(ctx, cfg)
	if err != nil || plan.Diags.HasErrors() {
		t.Fatalf("Build: %v\n%s", err, plan.Diags)
	}
	sum, err := Generate(ctx, cfg, plan, sqlc)
	if err != nil {
		t.Fatal(err)
	}
	if sum.Written != len(plan.Files) || sum.Removed != 1 || !sum.RanSQLC {
		t.Errorf("summary = %+v; want %d written, 1 removed, sqlc ran", sum, len(plan.Files))
	}

	exists := func(rel string) bool { _, err := os.Stat(cfg.Path(rel)); return err == nil }
	for _, rel := range []string{"schema/schema.sql", "sqlc.yaml", "gen/sqlcdb/models.go", "gen/sqlcdb/reports.sql.go", "gen/orders/v1/ordersdal/repository.go"} {
		if !exists(rel) {
			t.Errorf("%s was not generated", rel)
		}
	}
	if exists("queries/generated/old.sql") {
		t.Error("the stale generated file must be removed")
	}
	if !exists("queries/generated/NOTES.md") {
		t.Error("a file without the generated header must never be removed")
	}
	if got, _ := os.ReadFile(cfg.Path("queries/custom/reports.sql")); string(got) != custom {
		t.Error("custom queries must never be touched")
	}

	// The output compiles as part of the project... at least, sqlc accepted
	// the custom query alongside the generated ones (reports.sql.go exists).
	// A second run changes nothing.
	sum, err = Generate(ctx, cfg, plan, sqlc)
	if err != nil || sum.Written != 0 || sum.Unchanged != len(plan.Files) || sum.Removed != 0 {
		t.Errorf("second run = %+v, %v; want everything unchanged", sum, err)
	}
}

func TestGenerateRemovesStaleSQLCOutput(t *testing.T) {
	sqlc := sqlcOrSkip(t)
	ctx := context.Background()
	cfg := project(t, _yaml, "orders/v1/orders.proto")
	write(t, cfg.Path("gen/sqlcdb/gone.sql.go"), "// Code generated by sqlc. DO NOT EDIT.\npackage sqlcdb\n")

	plan, _ := Build(ctx, cfg)
	if _, err := Generate(ctx, cfg, plan, sqlc); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(cfg.Path("gen/sqlcdb/gone.sql.go")); err == nil {
		t.Error("stale sqlc output for a removed query file must be removed")
	}
}

func TestGenerateWithoutQueriesSkipsSQLC(t *testing.T) {
	ctx := context.Background()
	cfg := project(t, _yaml, "orders/v1/orders.proto")
	// Drop the store: entities only, no queries anywhere.
	p := cfg.Path("proto/orders/v1/orders.proto")
	src, _ := os.ReadFile(p)
	write(t, p, string(src[:strings.Index(string(src), "service OrderStore")]))

	plan, err := Build(ctx, cfg)
	if err != nil || plan.Diags.HasErrors() {
		t.Fatalf("Build: %v\n%s", err, plan.Diags)
	}
	sum, err := Generate(ctx, cfg, plan, "/nonexistent/sqlc") // must not be called
	if err != nil || sum.RanSQLC || !strings.Contains(sum.SQLCNote, "sqlc skipped") {
		t.Errorf("summary = %+v, %v; want sqlc skipped", sum, err)
	}
}

func TestCustomQueryNameCollision(t *testing.T) {
	cfg := project(t, _yaml, "orders/v1/orders.proto")
	write(t, cfg.Path("queries/custom/mine.sql"), "-- a report\n-- name: OrderGetById :one\nSELECT 1;\n-- name: OrderReport :many\nSELECT 1;\n")
	plan, err := Build(context.Background(), cfg)
	if err != nil {
		t.Fatal(err)
	}
	got := plan.Diags.String()
	if !strings.Contains(got, "queries/custom/mine.sql:2:1: error DAL205: custom query OrderGetById") || strings.Contains(got, "OrderReport") || len(plan.Files) != 0 {
		t.Errorf("findings =\n%s\nwant one DAL205 at mine.sql:2 and no files", got)
	}
}
